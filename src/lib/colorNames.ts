import chroma from "chroma-js";

// Pre-compute LAB values for all named colors
let _labCache: { name: string; lab: [number, number, number] }[] | null = null;
function getLabCache() {
  if (!_labCache) {
    _labCache = COLOR_NAMES.map(([name, hex]) => ({
      name,
      lab: chroma(hex).lab() as [number, number, number],
    }));
  }
  return _labCache;
}

export function nearestColorName(hex: string): string {
  const cache = getLabCache();
  const [l, a, b] = chroma(hex).lab();
  let best = "";
  let bestDist = Infinity;
  for (const { name, lab } of cache) {
    const dl = l - lab[0];
    const da = a - lab[1];
    const db = b - lab[2];
    const d = dl * dl + da * da + db * db;
    if (d < bestDist) {
      bestDist = d;
      best = name;
    }
  }
  return best;
}
